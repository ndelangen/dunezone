import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdtemp, readFile, rm, writeFile, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';

/* Rebuild the pinned, self-hosted listener. Normal app builds use these committed bytes and never download models. */
const root = path.resolve(import.meta.dirname, '..');
const output = path.join(root, 'public/tools/bidding-listener/v1');
const source = path.join(root, 'src/app/routes/_tool/tools/bidding/voiceAssets.generated.ts');
const archiveSources = {
  engine: {
    url: 'https://registry.npmjs.org/sherpa-onnx/-/sherpa-onnx-2.0.1.tgz',
    sha256: '031b235001fb41cc20ad405abe48e07891094047d6f462c9bdbb5a57434d2d54',
  },
  model: {
    url: 'https://github.com/k2-fsa/sherpa-onnx/releases/download/kws-models/sherpa-onnx-kws-zipformer-gigaspeech-3.3M-2024-01-01.tar.bz2',
    sha256: 'f170013b4716e41b62b9bfd809687c207cef798ef9bc6534d524e17af9b6561a',
  },
};
const sha256 = (bytes: Uint8Array | string) => createHash('sha256').update(bytes).digest('hex');
const temp = await mkdtemp(path.join(tmpdir(), 'bidding-listener-'));
try {
  for (const [name, archive] of Object.entries(archiveSources)) {
    const response = await fetch(archive.url);
    if (!response.ok) {
      throw new Error(`${name} download returned ${response.status}`);
    }
    const bytes = new Uint8Array(await response.arrayBuffer());
    if (sha256(bytes) !== archive.sha256) {
      throw new Error(`${name} archive integrity mismatch`);
    }
    const file = path.join(temp, `${name}.archive`);
    await writeFile(file, bytes);
    execFileSync('tar', ['-xf', file, '-C', temp]);
  }
  const pkg = path.join(temp, 'package');
  const model = path.join(temp, 'sherpa-onnx-kws-zipformer-gigaspeech-3.3M-2024-01-01');
  const engine = (await readFile(path.join(pkg, 'sherpa-onnx-wasm-nodejs.js'), 'utf8')).replaceAll(
    'globalThis.process',
    'process'
  );
  const kws = await readFile(path.join(pkg, 'sherpa-onnx-kws.js'), 'utf8');
  const exportAt = kws.lastIndexOf("if (typeof process == 'object'");
  if (exportAt < 0 || /new Function\b|\beval\s*\(/.test(engine + kws)) {
    throw new Error('The pinned engine packaging changed');
  }
  const banner = '/* sherpa-onnx 2.0.1, Apache-2.0. Generated by scripts/bidding-voice-assets.ts. */\n';
  const files: Record<string, { extension: string; bytes: Uint8Array | string }> = {
    engine: { extension: 'wasm', bytes: await readFile(path.join(pkg, 'sherpa-onnx-wasm-nodejs.wasm')) },
    encoder: {
      extension: 'onnx',
      bytes: await readFile(path.join(model, 'encoder-epoch-12-avg-2-chunk-16-left-64.int8.onnx')),
    },
    decoder: {
      extension: 'onnx',
      bytes: await readFile(path.join(model, 'decoder-epoch-12-avg-2-chunk-16-left-64.int8.onnx')),
    },
    joiner: {
      extension: 'onnx',
      bytes: await readFile(path.join(model, 'joiner-epoch-12-avg-2-chunk-16-left-64.int8.onnx')),
    },
    tokens: { extension: 'txt', bytes: await readFile(path.join(model, 'tokens.txt')) },
    glue: {
      extension: 'mjs',
      bytes: `${banner}export function makeEngine({process, require, Buffer}) { const __dirname = "/";\n${engine}\nreturn Module;\n}\n`,
    },
    spotter: { extension: 'mjs', bytes: `${banner}${kws.slice(0, exportAt)}\nexport { createKws };\n` },
  };
  await mkdir(output, { recursive: true });
  const assets: Record<string, { file: string; sha256: string; bytes: number }> = {};
  for (const [key, asset] of Object.entries(files)) {
    const digest = sha256(asset.bytes);
    const file = `${key}-${digest.slice(0, 12)}.${asset.extension}`;
    await writeFile(path.join(output, file), asset.bytes);
    assets[key] = { file, sha256: digest, bytes: Buffer.byteLength(asset.bytes) };
  }
  await writeFile(path.join(output, 'MODEL_README.md'), await readFile(path.join(model, 'README.md')));
  await writeFile(
    source,
    `/* Pinned local voice bytes. Regenerate with scripts/bidding-voice-assets.ts. */\nexport const VOICE_ASSET_ROOT = '/tools/bidding-listener/v1/';\nexport const VOICE_ASSETS = ${JSON.stringify(assets, null, 2)} as const;\n`
  );
  process.stdout.write(
    `Prepared ${Object.keys(assets).length} pinned voice assets. Preserve LICENSE.txt beside them.\n`
  );
} finally {
  await rm(temp, { recursive: true, force: true });
}
