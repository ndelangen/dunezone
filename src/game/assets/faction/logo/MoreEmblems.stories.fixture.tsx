export function SmallEmblems() {
  const samples = ['light', 'dark'].flatMap((tone) => [24, 32, 48, 72].map((size) => ({ tone, size })));
  return (
    <main style={{ padding: 28, background: '#eee5d2', color: '#252d35', minHeight: '100vh' }}>
      <h1 style={{ fontFamily: 'Caladea, serif', marginTop: 0 }}>Fifty emblems at small sizes</h1>
      <p>Each mark at 24, 32, 48, and 72 pixels on light and dark backgrounds.</p>
      <div style={{ overflowX: 'auto' }}>
        <table style={{ borderCollapse: 'separate', borderSpacing: '0 8px', minWidth: 820 }}>
          <thead>
            <tr>
              <th scope="col" style={{ textAlign: 'left' }}>
                Emblem
              </th>
              {samples.map(({ tone, size }) => (
                <th key={`${tone}-${size}`} scope="col" style={{ fontSize: 12, padding: 8 }}>
                  {size}px · {tone}
                </th>
              ))}
            </tr>
          </thead>
          <tbody>
            {Object.values(emblems).map(({ name, logo }) => (
              <tr key={logo}>
                <th scope="row" style={{ textAlign: 'left', fontSize: 14, paddingRight: 20 }}>
                  {name}
                </th>
                {samples.map(({ tone, size }) => (
                  <td
                    key={`${tone}-${size}`}
                    style={{
                      textAlign: 'center',
                      padding: 10,
                      background: tone === 'dark' ? '#101d2d' : '#faf5e9',
                      color: tone === 'dark' ? '#eee7d7' : '#252d35',
                    }}
                  >
                    <Mark logo={logo} size={size} />
                  </td>
                ))}
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </main>
  );
}
